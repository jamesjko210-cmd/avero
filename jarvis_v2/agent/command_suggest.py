"""Fuzzy "did you mean?" command suggestions for near-miss inputs.

When the planner finds no actions and the input is about to fall through to the
generic chat model, this module checks whether the input is a typo or near-miss
for a real Jarvis capability. If so, it returns a short, helpful suggestion that
points the owner at the working command — instead of a generic chat reply that
may wrongly claim Jarvis "can't" do something it actually can (e.g. "weathr in
tokyo" should suggest "weather in Tokyo", not deny weather lookups).

Design:
- Pure/stateless and dependency-light (only stdlib difflib + the curated command
  catalog already in capabilities). No model calls, no I/O, no side effects.
- Conservative: only fires on a strong fuzzy match so it never hijacks a genuine
  conversational turn. Returns None when unsure, so the chat fallback still runs.
"""

