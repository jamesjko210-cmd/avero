def _normalize(text: str) -> str:
    return " ".join(_TOKEN_RE.findall(str(text or "").lower()))


def _compact_text(text: str) -> str:
    return "".join(ch for ch in str(text or "").lower() if ch.isalnum())


def _iter_help_catalog_commands() -> tuple[str, ...]:
    """Return short help-promised commands without prose or placeholders."""
    commands: list[str] = []
    for topic, entries in HELP_SECTIONS.items():
        if topic not in _HELP_COMMAND_TOPICS:
            continue
        for entry in entries:
            raw = str(entry or "").strip()
            lowered = raw.lower()
            if not raw or lowered.startswith(_HELP_COMMAND_SKIP_PREFIXES):
                continue
            if any(fragment in raw for fragment in _HELP_COMMAND_SKIP_FRAGMENTS):
                continue
            command = raw.partition(":")[0].strip()
            if command and len(_normalize(command).split()) <= _MAX_INPUT_WORDS:
                commands.append(command)
    return tuple(commands)


@lru_cache(maxsize=1)
def _command_catalog() -> tuple[str, ...]:
    """All curated example commands, de-duplicated and normalized for matching."""
    seen: dict[str, str] = {}

    def add_command(command: str) -> None:
        norm = _normalize(command)
        if norm and norm not in seen:
            seen[norm] = str(command)
        prefix, sep, _ = str(command).partition(":")
        if sep:
            prefix_norm = _normalize(prefix)
            if prefix_norm and prefix_norm not in seen:
                seen[prefix_norm] = prefix.strip()

    for focus in EVERYDAY_FOCUS.values():
        for command in focus.get("commands", []) or []:
            add_command(str(command))
    for commands in STARTER_COMMANDS.values():
        for command in commands:
            add_command(str(command))
    for command in _iter_help_catalog_commands():
        add_command(command)
    for command in _RECOVERY_COMMANDS:
        add_command(command)
    # Keep the original (pretty) form keyed by its normalized variant.
    _command_catalog.pretty = seen  # type: ignore[attr-defined]
    return tuple(seen.keys())


def _pretty_for(norm: str) -> str:
    pretty = getattr(_command_catalog, "pretty", {})  # type: ignore[attr-defined]
    return pretty.get(norm, norm)


def suggest_command(user_input: str) -> str | None:
    """Return a one-line "Did you mean ...?" suggestion, or None if no strong match.

    Conservative by design: returns None for empty input, long prose, exact
    matches (those would have planned to a tool already), and anything below the
    similarity threshold — so the normal chat fallback still handles real turns.
    """
    compact = _compact_text(user_input)
    text_redirect = _TEXT_INTENT_REDIRECTS.get(compact)
    if text_redirect:
        return f"Did you mean: “{text_redirect}”? Send that and I'll run it."

    norm = _normalize(user_input)
    if not norm:
        return None

    redirect = _INTENT_REDIRECTS.get(norm)
    if redirect and _normalize(redirect) != norm:
        return f"Did you mean: “{redirect}”? Send that and I'll run it."

    if len(norm.split()) > _MAX_INPUT_WORDS:
        return None

    catalog = _command_catalog()
    if norm in catalog:
        # An exact catalog hit means the planner should already have routed it;
        # suggesting it back would be noise.
        return None

    matches = difflib.get_close_matches(norm, catalog, n=1, cutoff=_MIN_SIMILARITY)
    if not matches:
        return None
    best = matches[0]
    ratio = difflib.SequenceMatcher(None, norm, best).ratio()
    if ratio < _MIN_SIMILARITY:
        return None
    return f"Did you mean: “{_pretty_for(best)}”? Send that and I'll run it."
