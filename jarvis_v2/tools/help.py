def _help_handoff(*, topic: str, entries: list[str] | None = None, index: bool = False) -> dict[str, Any]:
    examples = list(entries or [])
    if index:
        section_rows = [
            {
                "topic": name,
                "entries": len(items),
                "preview": [_safe_text(item) for item in items[:3]],
                "command": f"help {name}",
            }
            for name, items in sorted(HELP_SECTIONS.items())
        ]
        entry_count = sum(row["entries"] for row in section_rows)
        preview = [_safe_text(item) for item in HELP_SECTIONS.get("core", [])[:3]]
    else:
        section_rows = [
            {
                "topic": topic,
                "entries": len(examples),
                "preview": [_safe_text(item) for item in examples[:5]],
                "command": f"help {topic}",
            }
        ]
        entry_count = len(examples)
        preview = [_safe_text(item) for item in examples[:8]]
    return {
        "source": "jarvis_help",
        "topic": topic,
        "index": index,
        "sections": len(section_rows),
        "entries": entry_count,
        "topics": sorted(HELP_SECTIONS),
        "section_rows": section_rows,
        "example_preview": preview,
        "next_commands": ["help", "capability map", "tool search: approvals", "risk matrix", "safety status"],
        "ready_for_operator": True,
        "changed": [],
        "authorizes_execution": False,
        "authorizes_completion_claim": False,
        "approval_granted": False,
        "content_in_handoff": False,
        "boundaries": _help_boundaries(),
    }


def _help_metadata(*, topic: str, entries: list[str] | None = None, index: bool = False) -> dict[str, Any]:
    handoff = _help_handoff(topic=topic, entries=entries, index=index)
    return _safe_metadata(
        topic=topic,
        sections=handoff["sections"],
        entries=handoff["entries"],
        help_handoff=handoff,
        help_handoff_ready=True,
        help_status="ok",
    )


def jarvis_help(args: dict[str, Any]) -> ToolResult:
    topic = _resolve_help_topic(str(args.get("topic") or ""))
    if topic and topic in HELP_SECTIONS:
        lines = [f"Jarvis help: {topic}"]
        lines.extend(f"- {item}" for item in HELP_SECTIONS[topic])
        return ToolResult("jarvis_help", True, "\n".join(lines), _help_metadata(topic=topic, entries=HELP_SECTIONS[topic]))

    lines = ["Jarvis help topics: " + ", ".join(sorted(HELP_SECTIONS))]
    lines.extend(["", describe_capabilities()])
    for name, examples in HELP_SECTIONS.items():
        lines.append(f"\n## {name.title()}")
        lines.extend(f"- {item}" for item in examples[:4])
    return ToolResult("jarvis_help", True, "\n".join(lines), _help_metadata(topic="index", index=True))
