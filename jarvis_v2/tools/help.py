def _resolve_help_topic(topic: str) -> str:
    normalized = " ".join(str(topic or "").strip().lower().replace("_", " ").replace("-", " ").split())
    if not normalized:
        return ""
    exact = HELP_TOPIC_ALIASES.get(normalized, normalized)
    if exact in HELP_SECTIONS:
        return exact

    candidates = sorted(set(HELP_SECTIONS) | set(HELP_TOPIC_ALIASES))
    matches = difflib.get_close_matches(normalized, candidates, n=1, cutoff=0.82)
    if not matches:
        return normalized
    match = matches[0]
    return HELP_TOPIC_ALIASES.get(match, match)


