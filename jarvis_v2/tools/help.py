def _safe_text(value: Any, *, limit: int = 180) -> str:
    text = " ".join(str(value or "").split())
    text = LOCAL_PATH_RE.sub("<local-path>", text)
    if len(text) > limit:
        return text[: max(0, limit - 1)].rstrip() + "…"
    return text


